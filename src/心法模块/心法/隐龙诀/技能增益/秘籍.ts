import { 属性类型 } from '@/@types/属性'
import { 技能增益列表类型 } from '@/@types/技能'

import 通用增益 from './通用增益/通用'

const 伤害秘籍 = (百分比: number, 名称 = `${百分比}%伤害`): 技能增益列表类型 => ({
  增益名称: 名称,
  增益所在位置: '秘籍',
  增益类型: '全局启用',
  增益集合: [{ 属性: 属性类型.通用增伤, 值: (百分比 * 10 + 1) / 1024 }],
})

const 会心秘籍 = (百分比: number): 技能增益列表类型 => ({
  增益名称: `${百分比}%会心`,
  增益所在位置: '秘籍',
  增益类型: '全局启用',
  增益集合: [{ 属性: 属性类型.外功会心百分比, 值: 百分比 / 100 }],
})

const 带秘籍 = (...秘籍: 技能增益列表类型[]) => [...通用增益, ...秘籍]

export const 星垂平野增益 = 带秘籍(
  会心秘籍(2),
  会心秘籍(3),
  会心秘籍(4),
  伤害秘籍(3),
  伤害秘籍(4),
  伤害秘籍(5),
)

export const 金戈回澜增益 = 带秘籍(会心秘籍(3), 会心秘籍(4), 伤害秘籍(4), 伤害秘籍(5))

