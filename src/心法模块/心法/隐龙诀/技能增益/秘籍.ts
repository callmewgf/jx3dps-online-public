const 伤害秘籍 = (百分比: number, 名称 = `${百分比}%伤害`): 技能增益列表类型 => ({
  增益名称: 名称,
  增益所在位置: '秘籍',
  增益类型: '全局启用',
  增益集合: [{ 属性: 属性类型.通用增伤, 值: (百分比 * 10 + 1) / 1024 }],
})

const 会心秘籍 = (百分比: number): 技能增益列表类型 => ({
  增益名称: `${百分比}%会心`,
  增益所在位置: '秘籍',
  增益类型: '全局启用',
  增益集合: [{ 属性: 属性类型.外功会心百分比, 值: 百分比 / 100 }],
})

const 带秘籍 = (...秘籍: 技能增益列表类型[]) => [...通用增益, ...秘籍]

const 增伤 = (
  名称: string,
  郭氏值: number,
  位置: 技能增益列表类型['增益所在位置'],
  类型: 技能增益列表类型['增益类型'],
): 技能增益列表类型 => ({
  增益名称: 名称,
  增益所在位置: 位置,
  增益类型: 类型,
  依赖奇穴: 位置 === '奇穴' ? 名称 : undefined,
  增益集合: [{ 属性: 属性类型.通用增伤, 值: 郭氏值 / 1024 }],
})

