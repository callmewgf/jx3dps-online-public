class 青山共我 extends 有CD技能通用类 {
  山河渊隙待生效跳: number[] = []

  constructor(模拟循环) {
    super(模拟循环)
    this.初始化技能运行数据()
  }

  命中() {
    // 山河渊隙持续 10 秒，每 0.5 秒一跳，共 20 跳；第一跳在 0.5 秒（不吃加速）
    const 当前时间 = this.模拟循环.当前时间 || 0
    for (let i = 1; i <= 20; i++) {
      this.山河渊隙待生效跳.push(当前时间 + 每秒郭氏帧 * 0.5 * i)
    }
    this.模拟循环.角色状态信息.青山标记结束时间 = 当前时间 + 每秒郭氏帧 * 10
    this.模拟循环.角色状态信息.青山可重置 = true
  }

  结算山河渊隙伤害(事件时间 = this.模拟循环.当前时间 || 0) {
    const 待结算 = this.山河渊隙待生效跳.filter((生效时间) => 生效时间 <= 事件时间)
    if (!待结算.length) return
    this.山河渊隙待生效跳 = this.山河渊隙待生效跳.filter((生效时间) => 生效时间 > 事件时间)
    待结算.forEach((生效时间) => {
      this.触发伤害行为('青山共我-山河渊隙', 1, [], 生效时间)
    })
  }
}

