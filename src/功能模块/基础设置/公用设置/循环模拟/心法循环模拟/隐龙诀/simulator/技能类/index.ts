class 寂洪荒 extends 有CD技能通用类 {
  constructor(模拟循环) {
    super(模拟循环)
    this.初始化技能运行数据()
  }

  命中() {
    // 双持链刃远距离命中：主手段(22604) + 副手段(22605) 各 1 段
    this.触发伤害行为('寂洪荒-主手')
    this.触发伤害行为('寂洪荒-副手')
    // 110级CW特效：辞光期间寂洪荒每次命中附带「寂洪荒·神兵」，
    // 且与金戈回澜一样叠加「乍起狂澜」DOT
    if (this.模拟循环.当前自身buff列表?.凌雪阁大橙武特效?.当前层数) {
      this.触发伤害行为('寂洪荒·神兵')
      this.模拟循环.技能类实例集合?.凌雪阁橙武DOT?.获得凌雪阁橙武DOT()
    }
    if (this.模拟循环.校验奇穴是否存在('风骨')) {
      this.模拟循环.角色状态信息.寂洪荒连击 += 1
      if (this.模拟循环.角色状态信息.寂洪荒连击 >= 3) {
        this.触发伤害行为('寂洪荒-风骨')
        this.模拟循环.角色状态信息.寂洪荒连击 = 0
      }
    }
    if (this.模拟循环.校验奇穴是否存在('百节')) {
      this.模拟循环.添加buff({ 名称: '百节', 对象: '自身' })
    }
    if (this.模拟循环.校验奇穴是否存在('渊岳')) {
      this.模拟循环.技能类实例集合?.寂洪荒DOT?.获得和刷新寂洪荒DOT()
    }
  }
}

class 飞刃回转 extends 有CD技能通用类 {
  // 每次施放产生一个独立刀气实体，各自维护待生效跳与频率倍率（支持隐风雷击退延长）
  刀气列表: { 待生效跳: number[]; 频率倍率: number }[] = []

  constructor(模拟循环) {
    super(模拟循环)
    this.初始化技能运行数据()
  }

  命中() {
    // 奇穴刀气 4.5 秒。第一跳在 0.5 秒，之后每 0.5 秒一跳，共 9 跳（不吃加速）。
    const 当前时间 = this.模拟循环.当前时间 || 0
    const 待生效跳: number[] = []
    for (let i = 1; i <= 9; i++) {
      待生效跳.push(当前时间 + 每秒郭氏帧 * 0.5 * i)
    }
    this.刀气列表.push({ 待生效跳, 频率倍率: 1 })
    // 命中后的血覆黄泉免调息窗口是 6 秒，不是刀气时长。
    this.模拟循环.角色状态信息.飞刃刀气结束时间 = 当前时间 + 每秒郭氏帧 * 6
  }

  // 飞刃回转奇穴：施展「隐风雷」将刀气击退，持续时间 +1 秒、攻击频率 +100%（最多增加至 200%）。
  // 对所有仍在生效的刀气生效：剩余跳按新间隔从当前时间重排，并顺延 1 秒上限。
  延长刀气() {
    const 当前时间 = this.模拟循环.当前时间 || 0
    this.刀气列表.forEach((刀气) => {
      const 待生效跳 = 刀气.待生效跳.filter((t) => t > 当前时间)
      if (!待生效跳.length) return
      刀气.频率倍率 = Math.min(刀气.频率倍率 + 1, 2)
      const 间隔 = (每秒郭氏帧 * 0.5) / 刀气.频率倍率
      const 新结束 = 待生效跳[待生效跳.length - 1] + 每秒郭氏帧
      const 新待生效跳: number[] = []
      for (let t = 当前时间 + 间隔; t <= 新结束; t += 间隔) {
        新待生效跳.push(Math.round(t))
      }
      刀气.待生效跳 = 新待生效跳
    })
  }

  结算刀气伤害(事件时间 = this.模拟循环.当前时间 || 0) {
    const 待结算: number[] = []
    this.刀气列表.forEach((刀气) => {
      const 到期跳 = 刀气.待生效跳.filter((t) => t <= 事件时间)
      if (!到期跳.length) return
      刀气.待生效跳 = 刀气.待生效跳.filter((t) => t > 事件时间)
      待结算.push(...到期跳)
    })
    this.刀气列表 = this.刀气列表.filter((刀气) => 刀气.待生效跳.length)
    待结算
      .sort((a, b) => a - b)
      .forEach((生效时间) => {
        this.触发伤害行为('飞刃回转', 1, [], 生效时间)
        // 青山共我标记：刀气跳伤害与直接技能一样会消耗标记并重置飞刃回转，
        // 所以飞刃存续期间打青山，下一跳刀气就会重置飞刃回转（每个青山窗口只生效一次）。
        this.尝试消耗青山标记(生效时间)
      })
  }

  尝试消耗青山标记(生效时间: number) {
    const 状态 = this.模拟循环.角色状态信息
    if (!状态.青山可重置) return
    if ((状态.青山标记结束时间 || 0) <= 生效时间) return
    状态.青山可重置 = false
    this.重置调息时间()
  }
}

