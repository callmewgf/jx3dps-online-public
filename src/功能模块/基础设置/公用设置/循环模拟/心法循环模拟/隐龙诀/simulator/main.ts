class 循环主类 {
  循环执行结果: '成功' | '异常' = '成功'
  循环异常信息 = { 异常索引: 0, 异常信息: '' as any }
  测试循环: string[] = []
  奇穴: string[] = []
  秘籍: 选中秘籍信息 = {}
  加速值 = 0
  网络延迟 = 0
  角色状态信息: 角色状态信息类型 = {
    寂洪荒连击: 0,
    蹈厉结束时间: 0,
    青山标记结束时间: 0,
    青山可重置: false,
  }
  当前自身buff列表: Buff枚举 = {}
  当前目标buff列表: Buff枚举 = {}
  当前时间 = 0
  战斗日志: 循环日志数据类型[] = []
  技能释放记录: 技能释放记录数据[] = []
  Buff和Dot数据: Buff枚举 = {}
  技能基础数据: 循环基础技能数据类型[] = []
  GCD组: 技能GCD组 = { 公共: 0, 自身: 0 }
  技能类实例集合: Record<string, any> = {}
  大橙武模拟 = false
  待生效事件队列: 待生效事件[] = []
  启用团队增益快照 = false
  团队增益轴: 团队增益轴类型 = {}
  副本事件实例列表: 副本事件实例类型[] = []

  constructor(props: SimulatorCycleProps) {
    this.测试循环 = props.测试循环
    this.大橙武模拟 = props.大橙武模拟
    this.奇穴 = props.奇穴
    this.秘籍 = props.秘籍
    this.加速值 = props.加速值
    this.网络延迟 = props.网络延迟
    this.启用团队增益快照 = !!props.启用团队增益快照
    this.团队增益轴 = props.团队增益轴 || {}
    this.副本事件实例列表 = props.副本事件实例列表 || []
    this.Buff和Dot数据 = 根据奇穴修改buff数据(this.奇穴, this.秘籍)
    this.技能基础数据 = 根据奇穴秘籍修改技能数据(this.奇穴, this.秘籍)
    this.当前自身buff列表 = { ...获取起手Buff配置(props?.起手Buff配置, this.Buff和Dot数据, '自身') }
    this.当前目标buff列表 = { ...获取起手Buff配置(props?.起手Buff配置, this.Buff和Dot数据, '目标') }
    this.初始化技能实例类()
    this.重置循环执行结果()
  }

  重置循环执行结果() {
    this.循环执行结果 = '成功'
    this.循环异常信息 = { 异常索引: 0, 异常信息: '' }
  }

  初始化技能实例类() {
    this.技能类实例集合 = {
      寂洪荒: new 寂洪荒(this),
      飞刃回转: new 飞刃回转(this),
      乱天狼: new 乱天狼(this),
      隐风雷: new 隐风雷(this),
      青山共我: new 青山共我(this),
      金戈回澜: new 金戈回澜(this),
      斩无常: new 斩无常(this),
      星垂平野: new 星垂平野(this),
      幽冥窥月: new 幽冥窥月(this),
      血覆黄泉: new 血覆黄泉(this),
      换行: new 换行(this),
      特效腰坠: new 特效腰坠(this),
      橙武特效: new 橙武特效(this),
      寂洪荒DOT: new 寂洪荒DOT(this),
      凌雪阁橙武DOT: new 凌雪阁橙武DOT(this),
    }
  }

  校验奇穴是否存在(待判断奇穴) {
    return this.奇穴?.includes(待判断奇穴)
  }

  添加buff({
    名称,
    对象 = '目标',
    事件时间 = this.当前时间,
    新增层数 = 1,
    覆盖层数 = 0,
    只添加日志 = false,
  }) {
    const 当前层数 =
      对象 === '自身'
        ? this.当前自身buff列表[名称]?.当前层数
        : this.当前目标buff列表[名称]?.当前层数
    const 新buff对象 = {
      ...this.Buff和Dot数据[名称],
      当前层数: 覆盖层数
        ? 覆盖层数
        : Math.min((当前层数 || 0) + 新增层数, this.Buff和Dot数据[名称]?.最大层数 || 1),
      刷新时间: 事件时间,
    }
    this.添加战斗日志({
      日志: `${对象}获得${名称}`,
      日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
      日志时间: 事件时间,
    })
    if (!只添加日志) {
      if (对象 === '自身') {
        this.当前自身buff列表[名称] = { ...新buff对象 }
      } else {
        this.当前目标buff列表[名称] = { ...新buff对象 }
      }
    }
  }

  卸除buff({ 名称, 对象 = '目标', 事件时间 = this.当前时间, 卸除层数 = 1 }) {
    const 当前层数 =
      (对象 === '自身'
        ? this.当前自身buff列表[名称]?.当前层数
        : this.当前目标buff列表[名称]?.当前层数) || 0
    if (当前层数 - 卸除层数 > 0) {
      const 新buff对象 = {
        ...this.Buff和Dot数据[名称],
        当前层数: 当前层数 - 卸除层数,
        刷新时间: this.当前时间,
      }
      if (对象 === '自身') {
        this.当前自身buff列表[名称] = { ...新buff对象 }
      } else {
        this.当前目标buff列表[名称] = { ...新buff对象 }
      }
    } else if (当前层数 > 0) {
      this.添加战斗日志({
        日志: `${对象}失去${名称}`,
        日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
        日志时间: 事件时间,
      })
      if (对象 === '自身') {
        delete this.当前自身buff列表[名称]
      } else {
        delete this.当前目标buff列表[名称]
      }
    }
  }

  增加时间(time) {
    if (time > 0) {
      const 新GCD组: 技能GCD组 = { 公共: 0, 自身: 0 }
      Object.keys(this.GCD组).forEach((key) => {
        新GCD组[key] = Math.max((this.GCD组[key] || 0) - time, 0)
      })
      this.GCD组 = { ...新GCD组 }
      this.当前时间 += time
      this.DOT结算与更新()
      this.清空已经消失的buff()
    }
  }

  技能释放前检查GCD统一方法(当前技能: 循环基础技能数据类型) {
    const 校验GCD组 = 当前技能.技能GCD组 === '自身' ? 当前技能.技能名称 : 当前技能.技能GCD组
    return (校验GCD组 && this.GCD组[校验GCD组]) || 0
  }

  技能GCD和CD处理(等待CD, 技能预估释放时间, 当前技能, 技能实例) {
    const 时间差 = 技能预估释放时间 - this.当前时间
    if (时间差 > 0) {
      this.增加时间(时间差)
    }
    if (等待CD) {
      this.添加战斗日志({
        日志: `【${当前技能?.技能名称}】等技能CD【${等待CD}】帧`,
        日志类型: '等CD',
        日志时间: 技能预估释放时间,
      })
    }
    const 待充能时间点 = 技能实例?.技能运行数据?.待充能时间点
    技能实例?.更新技能运行数据?.({
      待充能时间点: 待充能时间点?.filter((item) => item > 技能预估释放时间),
    })
  }

  技能释放后更新运行数据(当前技能: 循环基础技能数据类型, 技能实例) {
    if (!技能实例?.技能运行数据) return
    const 待充能时间点 = 技能实例.技能运行数据.待充能时间点 || []
    const 本次释放充能 =
      (待充能时间点[待充能时间点.length - 1] || this.当前时间) + (当前技能?.技能CD || 0)
    技能实例.更新技能运行数据({
      待充能时间点: [...待充能时间点, 本次释放充能],
    })
  }

  添加战斗日志(log: 循环日志数据类型) {
    const { 日志时间 = this.当前时间, ...rest } = log
    this.战斗日志.push({ 日志时间, ...rest })
  }

  技能造成伤害(
    来源,
    伤害次数 = 1,
    额外增益列表: string[] = [],
    造成时间 = this.当前时间,
    _隐藏日志 = false,
    技能等级 = 1,
  ) {
    const 当前技能数据 = 获取技能等级信息(
      技能系数?.find((item) => item.技能名称 === 来源),
      技能等级,
    )
    const 技能增益列表 = 当前技能数据?.技能增益列表 || []
    const 百节 = this.当前自身buff列表?.百节
    const 百节层数 = 百节?.当前层数 || 0
    const 百节仍在 =
      百节层数 > 0 &&
      造成时间 >= (百节?.刷新时间 || 0) &&
      造成时间 <= (百节?.刷新时间 || 0) + (百节?.最大持续时间 || 0)
    if (百节仍在) {
      const 百节增益名 = `百节·${百节层数}层`
      if (!额外增益列表.includes(百节增益名)) {
        额外增益列表 = 额外增益列表.concat(百节增益名)
      }
    }
    const 有关的buff列表 =
      技能增益列表
        ?.filter((item) => {
          const 当前增益数据 = 转化buff和增益名称(item.增益名称, this.当前自身buff列表, undefined)
          if (!当前增益数据) return false
          const 增益消失时间 = (当前增益数据?.刷新时间 || 0) + (当前增益数据?.最大持续时间 || 0)
          const 增益获得时间 = 当前增益数据?.刷新时间 || 0
          return 造成时间 <= 增益消失时间 && 造成时间 >= 增益获得时间
        })
        ?.map((item) => item.增益名称)
        ?.filter((item) => !额外增益列表.includes(item)) || []
    let 总增益列表 = 有关的buff列表.concat(额外增益列表)
    if (this.启用团队增益快照) {
      const 团队增益buff列表 = this.副本事件实例列表?.length
        ? 判断副本事件快照Buff(this.副本事件实例列表, this.当前时间 || 0)
        : 判断团队增益快照Buff({
            团队增益轴: this.团队增益轴,
            判定帧: this.当前时间 || 0,
          })
      if (团队增益buff列表?.length) {
        总增益列表 = 总增益列表.concat(团队增益buff列表)
      }
    }
    this.添加战斗日志({
      日志: 当前技能数据?.技能名称 || 来源,
      日志类型: '造成伤害',
      日志时间: 造成时间,
      buff列表: 总增益列表,
      其他数据: {
        伤害次数,
        技能等级,
      },
    })
  }

  检查GCD(当前技能: 循环基础技能数据类型, 技能实例, i) {
    if (技能实例?.检查GCD) {
      return 技能实例.检查GCD(i, 当前技能)
    }
    return this.技能释放前检查GCD统一方法(当前技能)
  }

  技能释放前(当前技能: 循环基础技能数据类型, 技能实例, i) {
    let GCD = 0
    if (i >= 0 && 当前技能?.技能GCD组) {
      GCD = this.检查GCD(当前技能, 技能实例, i)
    }
    const 延迟等待 = i > 0 && GCD ? this.网络延迟 : 0
    const 技能计划释放时间 = this.当前时间 + GCD + 延迟等待
    // 调息只更新技能按钮上的冷却和充能，不计入战斗时间。
    return {
      技能计划释放时间,
      技能预估释放时间: 技能计划释放时间,
      等待CD: 0,
    }
  }

  增加技能GCD(当前技能: 循环基础技能数据类型, 技能实例?) {
    if (!当前技能?.技能GCD组) return
    let 原始帧数 = 当前技能.技能释放后添加GCD
    if (当前技能.技能名称 === '斩无常') {
      const 跳数 = 技能实例?.本次作用次数 || 8
      原始帧数 = 8 * 跳数
    }
    const 实际添加GCD = 获取实际帧数(原始帧数, this.加速值)
    const 待更新GCD组 = 当前技能.技能GCD组 === '自身' ? 当前技能.技能名称 : 当前技能.技能GCD组
    this.GCD组[待更新GCD组] = (this.GCD组[待更新GCD组] || 0) + 实际添加GCD
  }

  增加技能CD(当前技能: 循环基础技能数据类型, 技能实例) {
    if (当前技能?.技能CD) {
      this.技能释放后更新运行数据(当前技能, 技能实例)
    }
  }

  减少技能调息(技能名称: string, 减少帧数: number) {
    const 技能实例 = this.技能类实例集合?.[技能名称]
    const 待充能时间点: number[] = 技能实例?.技能运行数据?.待充能时间点 || []
    if (!待充能时间点.length || 减少帧数 <= 0) return
    技能实例.更新技能运行数据({
      待充能时间点: 待充能时间点.map((时间) => Math.max(this.当前时间, 时间 - 减少帧数)),
    })
  }

  当前处于蹈厉() {
    return (this.角色状态信息.蹈厉结束时间 || 0) > this.当前时间
  }

  当前处于青山标记() {
    return (this.角色状态信息.青山标记结束时间 || 0) > this.当前时间
  }

  技能成功开始释放(当前技能: 循环基础技能数据类型, 技能实例) {
    // 风骨为累计计数：每 3 次寂洪荒触发一次，不被其他技能打断（实测 45 次 ≈ 寂洪荒施放数/3）
    this.增加技能GCD(当前技能, 技能实例)
    const 蹈厉免调息 = 当前技能.技能名称 === '寂洪荒' && this.当前处于蹈厉()
    const 飞刃免血覆 =
      当前技能.技能名称 === '血覆黄泉' && (this.角色状态信息.飞刃刀气结束时间 || 0) > this.当前时间
    // 辞光（buff 16482）：窗口内施展寂洪荒、金戈回澜都不计调息，不是打出金戈才清空两者。
    const 橙武生效 = !!this.当前自身buff列表?.凌雪阁大橙武特效?.当前层数
    const 橙武免调息 =
      橙武生效 && (当前技能.技能名称 === '金戈回澜' || 当前技能.技能名称 === '寂洪荒')
    // 青山标记只被自身伤害技能命中消耗并重置该技能调息：
    // 特效腰坠、橙武特效、换行等非伤害技能（技能类型「其他」）不吃标记。
    // 飞刃回转的刀气跳伤害在 结算刀气伤害 里消耗标记（刀气存续期间打青山会重置飞刃回转）。
    const 青山重置调息 =
      !!当前技能.技能CD &&
      当前技能.技能名称 !== '青山共我' &&
      当前技能.技能类型 !== '其他' &&
      this.当前处于青山标记() &&
      this.角色状态信息.青山可重置
    if (!蹈厉免调息 && !飞刃免血覆 && !橙武免调息) {
      this.增加技能CD(当前技能, 技能实例)
    }
    if (青山重置调息) {
      技能实例?.重置调息时间?.()
      this.角色状态信息.青山可重置 = false
    }
  }

  技能释放后(当前技能, 计划释放时间, 开始释放时间, 是否为读条技能, 技能实例) {
    this.技能释放记录.push({
      技能名称: 当前技能?.技能名称,
      计划释放时间,
      实际释放时间: 开始释放时间,
      是否为读条技能,
      技能释放记录结果: 技能实例?.获取技能释放记录结果?.() || {},
    })
  }

  清空已经消失的buff() {
    ;(['目标', '自身'] as const).forEach((对象) => {
      const buff列表 = 对象 === '自身' ? this.当前自身buff列表 : this.当前目标buff列表
      Object.keys(buff列表).forEach((key) => {
        const buff对象 = buff列表[key]
        const buff应该消失时间 = (buff对象?.刷新时间 || 0) + (buff对象?.最大持续时间 || 0)
        if (buff应该消失时间 < this.当前时间) {
          this.卸除buff({
            名称: key,
            对象,
            事件时间: buff应该消失时间,
            卸除层数: buff对象?.最大层数,
          })
        }
      })
    })
  }

  DOT结算与更新() {
    this.技能类实例集合?.寂洪荒DOT?.结算寂洪荒DOT伤害()
    this.技能类实例集合?.凌雪阁橙武DOT?.结算凌雪阁橙武DOT()
    this.技能类实例集合?.青山共我?.结算山河渊隙伤害?.()
    this.技能类实例集合?.飞刃回转?.结算刀气伤害?.()
  }

  本轮模拟开始前() {
    this.重置循环执行结果()
    this.待生效事件结算()
    this.DOT结算与更新()
  }

  本轮模拟结束后() {
    this.清空已经消失的buff()
    Object.keys(this.技能类实例集合).forEach((key) => {
      const 实例 = this.技能类实例集合[key]
      const 待充能时间点: number[] = 实例?.技能运行数据?.待充能时间点
      if (待充能时间点?.length) {
        实例.更新技能运行数据({
          待充能时间点: 待充能时间点.filter((item) => item > this.当前时间),
        })
      }
    })
  }

  技能释放校验(技能实例, 当前技能) {
    const 释放判断结果 = 技能实例.释放 ? 技能实例.释放() || { 可以释放: true } : { 可以释放: true }
    if (释放判断结果.可以释放) {
      this.添加战斗日志({
        日志: 当前技能?.技能名称,
        日志类型: '释放技能',
      })
    }
    return 释放判断结果
  }

  技能释放异常(校验结果, 当前技能, i) {
    this.添加战斗日志({
      日志: `循环在第${i + 1}个技能${当前技能?.技能名称}异常终止`,
      日志类型: '循环异常',
    })
    this.循环执行结果 = '异常'
    this.循环异常信息 = {
      异常索引: i + 1,
      异常信息: 校验结果?.异常信息,
    }
  }

  添加待生效事件队列(传入数据: 待生效事件[] = [], 覆盖 = false) {
    let 新队列 = [...(this.待生效事件队列 || [])]
    if (覆盖 && 传入数据[0]) {
      const 已有 = 新队列.some((item) => item.事件名称 === 传入数据[0].事件名称)
      新队列 = 已有
        ? 新队列.map((item) => (item.事件名称 === 传入数据[0].事件名称 ? 传入数据[0] : item))
        : 新队列.concat(传入数据)
    } else {
      新队列 = 新队列.concat(传入数据)
    }
    新队列.sort((a, b) => (a?.事件时间 || 0) - (b?.事件时间 || 0))
    this.待生效事件队列 = 新队列
  }

  待生效事件结算(结算判断时间 = this.当前时间) {
    const 轮训执行事件 = () => {
      if (this.待生效事件队列[0]?.事件时间 <= 结算判断时间) {
        const 当前事件 = this.待生效事件队列[0]
        this.DOT结算与更新()
        this.增加时间(当前事件.事件时间 - this.当前时间)
        if (当前事件.事件名称?.includes('卸除buff') && 当前事件?.事件备注?.buff名称) {
          this.卸除buff({
            名称: 当前事件.事件备注.buff名称,
            对象: 当前事件.事件备注.buff对象,
            卸除层数: 当前事件.事件备注.卸除层数,
          })
        }
        this.待生效事件队列.shift()
        if (this.待生效事件队列.length) {
          轮训执行事件()
        }
      }
    }
    if (this.待生效事件队列.length) {
      轮训执行事件()
    }
  }

  模拟() {
    for (let i = 0; i < this.测试循环.length; i++) {
      this.本轮模拟开始前()
      let 实例 = this.测试循环[i]
      let 额外信息 = null
      if (实例?.includes(技能额外信息分隔符)) {
        const list = 实例.split(技能额外信息分隔符)
        实例 = list[0]
        try {
          额外信息 = JSON.parse(list[1])
        } catch (error) {
          console.error(error)
        }
      }
      const 当前技能 = this.技能基础数据?.find((item) => item.技能名称 === 实例)
      const 技能实例 = 当前技能 ? this.技能类实例集合[当前技能.技能名称] : undefined
      if (当前技能 && 技能实例) {
        技能实例.释放前初始化?.(额外信息)
        const { 技能计划释放时间, 等待CD, 技能预估释放时间 } = this.技能释放前(
          当前技能,
          技能实例,
          i,
        )
        this.待生效事件结算(技能预估释放时间)
        this.技能GCD和CD处理(等待CD, 技能预估释放时间, 当前技能, 技能实例)
        this.技能成功开始释放(当前技能, 技能实例)
        const 释放校验结果 = this.技能释放校验(技能实例, 当前技能)
        const 开始释放时间 = this.当前时间
        if (释放校验结果?.可以释放) {
          技能实例.命中?.()
        } else {
          this.技能释放异常(释放校验结果, 当前技能, i)
          break
        }
        this.技能释放后(当前技能, 技能计划释放时间, 开始释放时间, false, 技能实例)
      }
      this.本轮模拟结束后()
    }
    const 收尾帧 = Math.max(0, ...Object.values(this.GCD组).map((帧) => 帧 || 0))
    this.增加时间(收尾帧)
  }

  日志排序() {
    this.战斗日志 = [...this.战斗日志].sort((a, b) => (a?.日志时间 || 0) - (b?.日志时间 || 0))
  }

  获取当前各技能的运行状态() {
    const 各技能当前运行状态 = {}
    Object.keys(this.技能类实例集合).forEach((key) => {
      各技能当前运行状态[key] = this.技能类实例集合[key]?.技能运行数据 || {}
    })
    return 各技能当前运行状态
  }

  获取各DOT的运行状态() {
    const DOT运行数据 = {}
    Object.keys(this.技能类实例集合).forEach((key) => {
      if (this.技能类实例集合[key]?.DOT运行数据) {
        DOT运行数据[key] = this.技能类实例集合[key].DOT运行数据
      }
    })
    return DOT运行数据
  }
}

export default 循环主类
